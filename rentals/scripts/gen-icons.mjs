// One-off icon generator: draws the Naptivity mark (amber "N" + star on deep
// navy) at 192px and 512px and writes src/icons.js with base64 PNG data.
// Run: node scripts/gen-icons.mjs
import zlib from "node:zlib";
import { writeFileSync } from "node:fs";

function crc32(buf) {
  let table = crc32.table;
  if (!table) {
    table = crc32.table = [];
    for (let n = 0; n < 256; n++) {
      let c = n;
      for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
      table[n] = c >>> 0;
    }
  }
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) c = table[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(body));
  return Buffer.concat([len, body, crc]);
}

function makePng(size) {
  const px = new Uint8Array(size * size * 4);
  const navy = [13, 34, 51], amber = [245, 166, 35], cream = [255, 244, 214];
  const set = (x, y, [r, g, b]) => {
    if (x < 0 || y < 0 || x >= size || y >= size) return;
    const i = (y * size + x) * 4;
    px[i] = r; px[i + 1] = g; px[i + 2] = b; px[i + 3] = 255;
  };
  for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) set(x, y, navy);
  const s = size / 512;
  const rect = (x0, y0, x1, y1, color) => {
    for (let y = Math.round(y0 * s); y < Math.round(y1 * s); y++)
      for (let x = Math.round(x0 * s); x < Math.round(x1 * s); x++) set(x, y, color);
  };
  // Letter N
  rect(120, 130, 180, 390, amber);
  rect(332, 130, 392, 390, amber);
  for (let t = 0; t < 64; t++) rect(168 + t * 2.6, 158 + t * 3.1, 196 + t * 2.6, 208 + t * 3.1, amber);
  // Star / moon dot top-right
  rect(398, 84, 414, 116, cream); rect(390, 92, 422, 108, cream);
  // Ground line
  rect(96, 404, 416, 420, cream);

  const raw = Buffer.alloc(size * (size * 4 + 1));
  for (let y = 0; y < size; y++) {
    raw[y * (size * 4 + 1)] = 0;
    Buffer.from(px.buffer, y * size * 4, size * 4).copy(raw, y * (size * 4 + 1) + 1);
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0); ihdr.writeUInt32BE(size, 4);
  ihdr[8] = 8; ihdr[9] = 6; // 8-bit RGBA
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk("IHDR", ihdr),
    chunk("IDAT", zlib.deflateSync(raw, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

const out = {
  icon192: makePng(192).toString("base64"),
  icon512: makePng(512).toString("base64"),
};
writeFileSync(new URL("../src/icons.js", import.meta.url),
  "// Generated by scripts/gen-icons.mjs — base64 PNG app icons (192 / 512).\n" +
  "export const ICON_192_B64 = " + JSON.stringify(out.icon192) + ";\n" +
  "export const ICON_512_B64 = " + JSON.stringify(out.icon512) + ";\n");
console.log("icons written", out.icon192.length, out.icon512.length);
